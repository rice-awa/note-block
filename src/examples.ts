/**
 * 示例曲库：五套现成编配，供示例面板一键载入。
 * 只依赖曲谱数据模型，不碰渲染层；midi 以 F#4 = 12 为基准（0..24，与游戏内音符盒音域一致），
 * 全部音符取自 D 大调五声音阶（F# A B D E），保持项目「一个调性、八个音色」的概念。
 */
import type { Note } from './song';

export interface Example {
  id: string;
  name: string;
  en: string;
  /** 氛围 / 律动 / 极简 —— 面板上的分类标签 */
  tag: string;
  bpm: number;
  bars: number;
  infinite: boolean;
  notes: Note[];
}

/** 行号 = ROWS 下标（草地 Harp、原木 Bass、沙 Snare、玻璃 Hat、羊毛 Guitar、铁块 Iron Xylo、金块 Bell、浮冰 Chime） */
const ROW = { harp: 0, bass: 1, snare: 2, hat: 3, guitar: 4, iron: 5, bell: 6, chime: 7 } as const;

/** [step, midi] 列表 → 某一行的音符 */
const track = (row: number, cells: ReadonlyArray<readonly [number, number]>): Note[] =>
  cells.map(([step, midi]) => ({ step, row, midi }));

const merge = (...parts: Note[][]): Note[] => parts.flat();

